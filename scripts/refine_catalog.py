def pick(a: b.Achievement, topic: str, round_no: int, used: set[str]) -> str:
    pool = POOLS[topic]
    digest = hashlib.sha256(f"{a.key}|{topic}|{round_no}".encode()).digest()
    start = int.from_bytes(digest[:4], "big") % len(pool)
    for offset in range(len(pool)):
        sentence = pool[(start + offset) % len(pool)]
        if sentence not in used:
            return sentence
    return pool[start]


