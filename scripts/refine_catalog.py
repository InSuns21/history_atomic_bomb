def compact_len(s: str) -> int:
    return len(re.sub(r"\s+", "", s))


def strip_bootstrap(body: str) -> str:
    out = body
    for filler in BOOTSTRAP_FILLER:
        out = out.replace(filler, "")
    return out.strip()


