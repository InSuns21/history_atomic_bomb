    if line.startswith('|') and line.rstrip().endswith('|'):
        cells=[c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells)>=4 and cells[0] not in {'年月','年月日'} and not all(re.fullmatch(r':?-{3,}:?',c.replace(' ','')) for c in cells):
            title=re.sub(r'\*\*(.*?)\*\*',r'\1',cells[1]).strip()
            old=[t.strip() for t in re.split(r'[,、]+',cells[2]) if t.strip()]
            new=normalize(old,title,section)
            if old!=new:
                cells[2]=' '+', '.join(new)+' '
                lines[i]='|'.join(['']+cells+[''])
                changed+=1
    if line.startswith('### '):
        title=re.sub(r'\*\*','',line[4:]).strip()
        # Standalone achievements have a **タグ:** line below them.
        j=i+1
        while j<len(lines) and not lines[j].startswith('## ') and not lines[j].startswith('### '):
            if lines[j].strip().startswith('**タグ:**'):
                old=[t.strip() for t in re.split(r'[,、]+',lines[j].replace('**タグ:**','').replace('**','')) if t.strip()]
                new=normalize(old,title,section)
                if old!=new:
                    lines[j]='**タグ:** '+', '.join(new)
                    changed+=1
                break
            j+=1

