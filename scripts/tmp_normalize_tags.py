def normalize(tags, title, section):
    tags=[t for t in tags if t not in {'広島・長崎','原潜・SLBM','原発事故'}]
    s=set(tags)
    # Section 2 used to add these indiscriminately. Re-add only where semantically justified.
    if section.startswith('2.'):
        s.discard('被爆後'); s.discard('復興')
        if title in POSTBOMB: s.add('被爆後')
        if title in RECONSTRUCTION: s.add('復興')
        s.discard('広島'); s.discard('長崎')
        if title in HIROSHIMA or title in BOTH: s.add('広島')
        if title in NAGASAKI or title in BOTH: s.add('長崎')
    elif section.startswith('1.'):
        s.discard('広島'); s.discard('長崎')
        if title in HIROSHIMA or title in BOTH: s.add('広島')
        if title in NAGASAKI or title in BOTH: s.add('長崎')
    if section.startswith('4.'):
        s.discard('デュアルユース')
        if title in DUAL_USE: s.add('デュアルユース')
    if title in ACCIDENTS: s.add('原子力事故')
    s -= REMOVE.get(title,set())
    s |= ADD.get(title,set())
    return sorted(s,key=lambda t:(rank.get(t,999),t))

